WEATHERS = ["clear", "cloudy", "rain", "rain"]


def congestion_level(occupancy_percent: float) -> str:
    if occupancy_percent < 40:
        return "Low"
    if occupancy_percent < 65:
        return "Moderate"
    if occupancy_percent < 85:
        return "High"
    return "Severe"


def _rush_factor(ts: datetime) -> float:
    hour = ts.hour + ts.minute / 60.0
    # Morning rush 08:00-10:00, evening rush 17:00-19:30, Gaussian bumps.
    morning = 0.85 * math.exp(-((hour - 9.0) ** 2) / (2 * 0.9 ** 2))
    evening = 1.0 * math.exp(-((hour - 18.0) ** 2) / (2 * 1.1 ** 2))
    midday = 0.25 * math.exp(-((hour - 13.0) ** 2) / (2 * 1.5 ** 2))
    night = -0.35 if hour < 5.5 else 0.0
    return 1.0 + morning + evening + midday + night


def _weather_for(ts: datetime, rng: random.Random) -> str:
    # Deterministic-ish weather: rainy on some seeded days, otherwise clear/cloudy.
    if (ts.timetuple().tm_yday % 5) == 3 and 6 <= ts.hour <= 20:
        return "rain"
    return rng.choice(["clear", "clear", "cloudy"])


@dataclass
class Reading:
    intersection_id: str
    sensor_id: str
    timestamp: str
    vehicle_count: int
    avg_speed_kmh: float
    occupancy_percent: float
    queue_length: int
    weather: str
    event: bool
    congestion: str

    def to_dict(self):
        return asdict(self)


def generate_reading(intersection: dict, ts: datetime, rng: random.Random) -> Reading:
    weather = _weather_for(ts, rng)
    weekend = ts.weekday() >= 5
    factor = _rush_factor(ts)
    if weekend:
        factor *= 0.72
    if weather == "rain":
        factor *= 1.18
    event = (ts.weekday() == 4 and 17 <= ts.hour < 21 and intersection["id"] in ("INT-A", "INT-B"))
    if event:
        factor *= 1.25
    noise = rng.gauss(0, 0.08)
    count = max(4, int(round(intersection["base_volume"] * factor * (1 + noise))))
    occupancy = min(98.0, max(5.0, round(count / intersection["capacity_per_5min"] * 100, 1)))
    # Speed falls as occupancy rises.
    speed = round(max(8.0, 58.0 - occupancy * 0.45 + rng.gauss(0, 2.0)), 1)
    queue = max(0, int(round((occupancy - 45) / 6.0))) if occupancy > 45 else 0
    return Reading(
        intersection_id=intersection["id"],
        sensor_id=intersection["sensor_id"],
        timestamp=ts.astimezone(timezone.utc).isoformat().replace("+00:00", "Z"),
        vehicle_count=count,
        avg_speed_kmh=speed,
        occupancy_percent=occupancy,
        queue_length=queue,
        weather=weather,
        event=event,
        congestion=congestion_level(occupancy),
    )


def generate_history(intersection_id: str, days: int = 7, seed: int = 42, end: datetime | None = None) -> list[Reading]:
    """Synthetic 5-minute readings, oldest first, ending at `end` (UTC)."""
    inter = next(i for i in INTERSECTIONS if i["id"] == intersection_id)
    rng = random.Random(seed + sum(ord(c) for c in intersection_id) % 1000)
    end = end or datetime.now(timezone.utc)
    # Align to a 5-minute boundary.
    end = end.replace(minute=(end.minute // 5) * 5, second=0, microsecond=0)
    steps = days * 24 * 12
    out: list[Reading] = []
    for n in range(steps, 0, -1):
        ts = end - timedelta(minutes=5 * n)
        out.append(generate_reading(inter, ts, rng))
    return out


def latest_reading(intersection_id: str, seed: int = 42) -> Reading:
    return generate_history(intersection_id, days=1, seed=seed)[-1]
